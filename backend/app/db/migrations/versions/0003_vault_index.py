# One function decides visibility, so every table follows the same rule:
#   - some access row (owner or shared space) is readable at the user's level
#   - drafts / in-review notes: only their author or a reviewer of that space
# SECURITY DEFINER lets the policy read documents without recursing into RLS.
DOC_VISIBLE = """
CREATE OR REPLACE FUNCTION sop_doc_visible(doc uuid) RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (
    SELECT 1 FROM documents d
    JOIN document_access a ON a.document_id = d.id
    WHERE d.id = doc
      AND sop_sensitivity_rank(a.sensitivity) <= sop_scope_rank(a.space)
      AND (
        d.status NOT IN ('draft', 'in_review')
        OR d.author_id::text = NULLIF(current_setting('sop.user_id', true), '')
        OR (NULLIF(current_setting('sop.review_spaces', true), '')::jsonb ? a.space)
      )
  )
$$
"""
